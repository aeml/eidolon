import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = new URL('../server/internal/game/content/world-locations.json', import.meta.url);
const entries = JSON.parse(fs.readFileSync(source, 'utf8'));
const ids = new Set(), entities = new Set();
for (const entry of entries) {
    if (!/^[a-z][a-z0-9-]+$/.test(entry.id) || ids.has(entry.id) ||
        !entry.entityId || entities.has(entry.entityId) || !entry.name ||
        !['story', 'service', 'portal'].includes(entry.kind) || typeof entry.instanceId !== 'string' ||
        !Number.isFinite(entry.x) || !Number.isFinite(entry.z)) throw new Error('Invalid world location registry');
    ids.add(entry.id); entities.add(entry.entityId);
}
const output = `// Generated by scripts/generate-world-locations.mjs; edit the canonical server JSON.\nexport const WORLD_LOCATIONS = Object.freeze(${JSON.stringify(entries, null, 2)}.map(Object.freeze));\n`;
const target = fileURLToPath(new URL('../src/data/worldLocations.generated.js', import.meta.url));
if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Stale client world locations');
} else fs.writeFileSync(target, output);
console.log(`Verified ${entries.length} shared world locations.`);
