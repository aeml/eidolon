import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import {
    ABILITY_VISUAL_ALIASES,
    getAbilityRuneVariants,
    listPlayerAbilityPresentations
} from '../src/skills/abilityVisualManifest.js';
import { listActorAnimationEntries } from '../src/entities/actorAnimationManifest.js';
import {
    ACTOR_STATUS_VISUAL_STATES,
    getStatusVisualDefinition
} from '../src/entities/AttachedStatusEffect.js';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(repoRoot, 'docs', 'ANIMATION_COVERAGE.md');
const abilities = listPlayerAbilityPresentations();
const actors = listActorAnimationEntries();

const escapeCell = (value) => String(value ?? '—')
    .replaceAll('|', '\\|')
    .replaceAll('\n', '<br>');

const table = (headers, rows) => [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map(escapeCell).join(' | ')} |`)
].join('\n');

const aliasRows = Object.entries(ABILITY_VISUAL_ALIASES).flatMap(([className, aliases]) =>
    Object.entries(aliases).map(([alias, canonical]) => [className, alias, canonical])
);

const abilityRows = abilities.map((ability) => {
    const runes = getAbilityRuneVariants(ability.className, ability.skillName);
    const layers = ability.layers.map((entry) => `${entry.type}@${entry.anchor}`).join(', ');
    return [
        ability.className,
        ability.skillName,
        ability.category,
        ability.animation,
        layers,
        ability.persistentState || 'none',
        ability.local,
        ability.remote,
        runes.length ? runes.map((rune) => `${rune.name} (${rune.id})`).join('<br>') : 'none'
    ];
});

const actorRows = actors.map((actor) => [
    actor.type,
    actor.category,
    actor.source,
    actor.states.join(', '),
    actor.jump,
    actor.special,
    actor.browserEvidence
]);

const statusRows = Object.keys(ACTOR_STATUS_VISUAL_STATES).map((statusKey) => {
    const visual = getStatusVisualDefinition(statusKey);
    return [statusKey, visual.style, `#${visual.color.toString(16).padStart(6, '0')}`, visual.radius];
});

const content = `# Animation and Ability Visual Coverage

This file is generated by \`npm run docs:animations\`. Edit the canonical manifests, not the tables below.

## Coverage contract

- Source of truth for selectable active abilities: \`src/skills/abilityVisualManifest.js\`.
- Source of truth for shipped actor clips and intentional fallbacks: \`src/entities/actorAnimationManifest.js\`.
- Source of truth for persistent actor-attached state visuals: \`src/entities/AttachedStatusEffect.js\`.
- Server configuration parity, alias resolution, rune ownership, explicit local/remote classification, and the exact 52-ability count are enforced by \`tests/AbilityVisualManifest.test.js\`.
- Actor clip declarations and production mesh coverage are enforced by \`tests/ActorAnimationManifest.test.js\`, \`tests/ActorAnimationState.test.js\`, and \`tests/MeshFactoryLoader.test.js\`.
- The deterministic production gallery is \`repro.html?gallery=1\`; \`tests/e2e/animation-gallery.spec.js\` renders all entries in hardware Chrome at High and Low quality.
- Live production evidence is recorded separately in \`docs/plans/live-browser-qa-checklist.md\`; a manifest entry does not itself claim live observation.

True passive talents do not create a cast action and are intentionally excluded from the active ability count. Rune, talent, equipment, and compatibility names that alter an active ability must resolve to one of the explicit entries below. A passive that creates a persistent visible actor state must instead be added to the attached-state table.

## Selectable active abilities (${abilities.length})

${table(
    ['Class', 'Canonical ability', 'Category', 'Actor profile', 'Cast/impact layers', 'Persistent route', 'Local', 'Remote', 'Rune variants'],
    abilityRows
)}

## Compatibility aliases (${aliasRows.length})

Aliases reuse the canonical composition deliberately; they are tested so a server compatibility name cannot fall through to an unclassified generic effect.

${table(['Class', 'Alias', 'Canonical presentation'], aliasRows)}

## Actor animation inventory (${actors.length})

Player classes declare Idle/Walk/Run/Attack/Death clips through either the shared procedural humanoid rig or a remaining imported rig. No player currently has a dedicated Jump clip, so Jump uses an intentional procedural arc/lean synchronized to the best locomotion clip. Procedural enemies and bosses receive deterministic generated Idle/Walk/Run/Attack/Death clips. NPCs that never move or fight are explicitly Idle-only.

${table(['Actor', 'Category', 'Source', 'Declared clips', 'Jump', 'Special behavior', 'Browser evidence'], actorRows)}

## Persistent and crowd-control actor states (${statusRows.length})

These effects are world-space groups: they follow actor position without inheriting imported model scale or facing. Server-replicated booleans and remaining durations reconstruct combat buffs/debuffs on local and remote actors after full state, delta state, reconnect, and join-in-progress. Spirit Guardians uses its dedicated orbit implementation and is therefore listed in the ability table rather than this shared attached-state table.

${table(['State key', 'Visual composition', 'Primary color', 'Radius'], statusRows)}

## Rendering and lifecycle expectations

- Every active ability has a named actor animation profile and one or more explicit production transient layers.
- Persistent abilities additionally use an attached actor state, authoritative zone/trap entity, dedicated Spirit Guardians effect, or production summon entity.
- Effect origin/target anchors, local/remote presentation, cleanup, repeated casts, non-finite transforms, visible mesh counts, and Low/High behavior are checked in the gallery and focused lifecycle tests.
- Server removal controls authoritative trap and ground-zone lifetime. Actor death, replacement, scene clear, and disposal cancel managed timers and remove attached nodes once.
- Production-model limitations are stated rather than hidden: no dedicated player Jump/Hit clips currently ship, and generated actors are intentionally code-animated. Future code-native states must update the actor manifest and its regression tests rather than falling through to imported or generic animation.

## Evidence status

- Inventory and explicit classification: implemented and unit tested.
- Deterministic local/remote gallery: all 112 base/rune presentations and all ${actors.length} actor entries pass at High and Low in hardware Chrome; the release checklist records the renderer and release-specific run.
- Real-input gameplay: all four dedicated class routes cover idle/run/jump/basic attack/death, 52 selectable abilities, and 60 rune variants. The two-browser route covers remote persistent aura refresh/reconstruction/cleanup, summon, ground, projectile, teleport, movement, jump, and combat convergence.
- Multiplayer and live production: must be re-run for each release SHA and are not implied by this generated document.
`;

await writeFile(outputPath, content, 'utf8');
console.log(`Wrote ${path.relative(repoRoot, outputPath)} (${abilities.length} abilities, ${actors.length} actors)`);
