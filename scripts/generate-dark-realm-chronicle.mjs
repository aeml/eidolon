import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const chapters = JSON.parse(fs.readFileSync(path.join(root, 'server/internal/game/content/dark-realm-chronicle.json'), 'utf8'));
const districts = new Set(['unwritten_shore', 'tithe_of_names', 'stillwater_foundry', 'city_without_tomorrow']);
const models = new Set(['flood_shelter', 'ruined_house', 'observatory', 'command_stone', 'horizon_marker', 'cold_kiln', 'root_memory', 'root_growth', 'tide_lens']);
const ids = new Set(), siteIds = new Set(), items = new Set();
for (const chapter of chapters) {
    if (!/^chronicle_dark_[a-z_]+$/.test(chapter.id) || ids.has(chapter.id) || !districts.has(chapter.district)
        || !['INVESTIGATE', 'KILL', 'COLLECT'].includes(chapter.type)) throw new Error(`Invalid chapter: ${chapter.id}`);
    ids.add(chapter.id);
    for (const field of ['title', 'acceptance', 'completion', 'summary']) {
        if (typeof chapter[field] !== 'string' || !chapter[field].trim()) throw new Error(`Missing ${chapter.id}/${field}`);
    }
    if (chapter.type === 'INVESTIGATE') {
        if (!Array.isArray(chapter.sites) || !chapter.sites.length || chapter.sites.length > 32) throw new Error(`Invalid discoveries: ${chapter.id}`);
        const earlier = new Set();
        for (const site of chapter.sites) {
            if (!/^dark_[a-z_]+$/.test(site.id) || siteIds.has(site.id) || site.kind !== 'inspect' || !models.has(site.model)
                || ![site.x, site.z].every(Number.isFinite) || !site.title?.trim() || !site.text?.trim()
                || (site.requires && !earlier.has(site.requires))) throw new Error(`Invalid discovery: ${site.id}`);
            earlier.add(site.id); siteIds.add(site.id);
            site.entityId = `chronicle-site-${site.id}`;
        }
    } else {
        if (!['DissonantShade', 'MemoryReaver'].includes(chapter.enemy) || !Number.isInteger(chapter.count) || chapter.count <= 0) throw new Error(`Invalid objective: ${chapter.id}`);
        if (chapter.type === 'COLLECT') {
            if (!chapter.item?.trim() || items.has(chapter.item)) throw new Error(`Invalid item: ${chapter.id}`);
            items.add(chapter.item);
        }
    }
    chapter.realm = 'dark';
    chapter.instanceId = 'dark-realm';
    chapter.catchupAcceptance = `You have already earned passage beyond this part of the expedition. Help me preserve the missing account of “${chapter.title}”. This is optional Chronicle work; your existing access will not change.`;
    chapter.catchupCompletion = `This account joins the Chronicle. ${chapter.summary}`;
}
if (chapters.length !== 24 || siteIds.size !== 38 || items.size !== 4) throw new Error('Incomplete Dark Realm campaign');
const target = path.join(root, 'src/data/darkRealmChronicle.generated.js');
const output = `// Generated by scripts/generate-dark-realm-chronicle.mjs. Do not edit.\nexport const darkRealmChapters = ${JSON.stringify(chapters, null, 2)};\n`;
if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Stale Dark Realm Chronicle content');
} else fs.writeFileSync(target, output);
console.log('Verified 24 Dark Realm chapters, 38 discoveries, and four collection items.');
