import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = new URL('../server/internal/game/content/world-geography.json', import.meta.url);
const data = JSON.parse(fs.readFileSync(source, 'utf8'));
const ids = new Set();
if (!Number.isFinite(data.fenceStep) || data.fenceStep < 1 || data.fenceStep > 100) throw new Error('Invalid fence step');
for (const r of data.regions) {
    if (!r.id || ids.has(r.id) || !r.name ||
        ![r.minX, r.maxX, r.minZ, r.maxZ].every(Number.isFinite) ||
        r.minX >= r.maxX || r.minZ >= r.maxZ || r.maxX - r.minX > 10000 || r.maxZ - r.minZ > 10000) {
        throw new Error('Invalid world region');
    }
    ids.add(r.id);
    const sides = new Set();
    for (const wall of r.walls) {
        if (sides.has(wall.side) || !['north', 'south', 'west', 'east'].includes(wall.side)) throw new Error('Invalid world wall');
        sides.add(wall.side);
        const vertical = ['west', 'east'].includes(wall.side);
        const min = vertical ? r.minZ : r.minX, max = vertical ? r.maxZ : r.maxX;
        if (wall.gap !== undefined && (!Array.isArray(wall.gap) || wall.gap.length !== 2 ||
            !wall.gap.every(Number.isFinite) || wall.gap[0] <= min || wall.gap[1] >= max || wall.gap[0] >= wall.gap[1])) {
            throw new Error('Invalid world gate');
        }
    }
}
if (ids.size !== 5 || !['earth', 'town', 'water', 'fire', 'air'].every(id => ids.has(id))) throw new Error('Missing overworld region');
const output = `// Generated by scripts/generate-world-geography.mjs; edit the canonical server JSON.
const freeze = value => {
    if (value && typeof value === 'object') {
        Object.values(value).forEach(freeze);
        Object.freeze(value);
    }
    return value;
};
export const WORLD_GEOGRAPHY = freeze(${JSON.stringify(data, null, 2)});
`;
const target = fileURLToPath(new URL('../src/data/worldGeography.generated.js', import.meta.url));
if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Stale client world geography');
} else fs.writeFileSync(target, output);
console.log(`Verified ${ids.size} shared world regions.`);
