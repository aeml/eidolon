import fs from 'node:fs';
import { WORLD_REGIONS } from '../src/data/worldGeography.js';
import { EARTH_LOCATIONS } from '../src/data/worldPopulation.js';

// Shared data for the elevation integration candidate. Generating this file
// does not activate raised terrain in either live movement or rendering.
const source = new URL('../server/internal/game/content/world-elevation-recipe.json', import.meta.url);
const recipe = JSON.parse(fs.readFileSync(source, 'utf8'));
if (recipe.schemaVersion !== 1 || recipe.region !== 'earth' || recipe.spacing !== 16 || recipe.inset !== .75 ||
    ![recipe.edgeFade, recipe.padFade, recipe.maxGrade].every(value => Number.isFinite(value) && value > 0) ||
    recipe.hills.length < 1 || recipe.hills.length > 32) throw new Error('Invalid elevation recipe');
const ids = new Set();
for (const hill of recipe.hills) {
    if (!hill.id || ids.has(hill.id) || ![hill.x, hill.z, hill.radiusX, hill.radiusZ, hill.height].every(Number.isFinite) ||
        hill.radiusX < 32 || hill.radiusZ < 32 || hill.height < 0 || hill.height > 32) throw new Error('Invalid terrain hill');
    ids.add(hill.id);
}
const earth = WORLD_REGIONS.earth, town = WORLD_REGIONS.town;
const data = { ...recipe,
    bounds: { minX: earth.minX + recipe.inset, maxX: earth.maxX - recipe.inset,
        minZ: earth.minZ + recipe.inset, maxZ: earth.maxZ - recipe.inset },
    // Keep town, gates and existing story/dungeon landings flat. Paths between
    // them may climb; these pads do not change access, safety or collision.
    flatTown: { minX: town.minX - 24, maxX: town.maxX + 24, minZ: town.minZ - 24, maxZ: town.maxZ + 24 },
    // A full cell diagonal, not half a cell: triangle interpolation must not
    // bring a raised outside vertex into an existing landmark footprint.
    pads: EARTH_LOCATIONS.map(({ id, x, z, radius }) => ({ id, x, z, radius: radius + Math.ceil(recipe.spacing * Math.SQRT2) }))
};
const json = JSON.stringify(data, null, 2);
const outputs = [
    [new URL('../server/internal/game/content/world-elevation.json', import.meta.url), `${json}\n`],
    [new URL('../src/data/worldElevation.generated.js', import.meta.url),
        `// Generated by scripts/generate-world-elevation.mjs; not yet enabled in live gameplay.\nexport const WORLD_ELEVATION = ${json};\n`]
];
for (const [path, output] of outputs) {
    if (process.argv.includes('--check')) {
        if (fs.readFileSync(path, 'utf8') !== output) throw new Error(`Stale elevation data: ${path.pathname}`);
    } else fs.writeFileSync(path, output);
}
console.log(`Verified ${ids.size} Earth terrain forms and ${data.pads.length} preserved landings.`);
