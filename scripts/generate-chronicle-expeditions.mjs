import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: generate-chronicle-expeditions.mjs [--check]');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = name => JSON.parse(fs.readFileSync(path.join(root, 'server/internal/game/content', name), 'utf8'));
const chapters = read('chronicle-expeditions.json');
const investigations = read('chronicle-investigations.json').chapters;
const hunts = read('chronicle-hunts.json');
const questSource = fs.readFileSync(path.join(root, 'server/internal/game/quests.go'), 'utf8');
const constants = new Map([...questSource.matchAll(/(Chronicle\w+ID)\s*=\s*"([^"]+)"/g)].map(match => [match[1], match[2]]));
const classicSource = questSource.split('func classicChronicleQuestCatalog()')[1].split('\nfunc ')[0];
const classic = [...classicSource.matchAll(/\bID:\s*(?:"([^"]+)"|(Chronicle\w+ID))/g)].map(match => match[1] || constants.get(match[2]));
if (classic.length !== 15 || classic.some(id => !id)) throw new Error('Unrecognized classic Chronicle catalog');
const originalIds = new Set([...classic, ...investigations.map(q => q.id), ...hunts.map(q => q.id)]);
const ids = new Set(chapters.map(q => q.id));
if (ids.size !== chapters.length) throw new Error('Duplicate expedition identity');
const allIds = new Set([...originalIds, ...ids]);
const siteIds = new Set(investigations.flatMap(q => q.sites.map(s => s.id)));
const bounds = {earth: [-1000,1000,-600,1000], water: [-1000,1000,-2200,-600], fire: [-3000,-1000,-600,1000], air: [1000,3000,-600,1000]};
for (const q of chapters) {
    if (!/^chronicle_[a-z_]+$/.test(q.id) || originalIds.has(q.id) || !allIds.has(q.beforeQuestId) || !allIds.has(q.previousQuestId)) throw new Error(`Invalid expedition placement: ${q.id}`);
    if (!['KILL','INVESTIGATE'].includes(q.type) || !bounds[q.realm]) throw new Error(`Invalid expedition objective: ${q.id}`);
    for (const field of ['title','acceptance','completion','handoff','lore','catchupAcceptance','catchupCompletion']) {
        if (typeof q[field] !== 'string' || !q[field].trim() || /[<>]/.test(q[field])) throw new Error(`Missing or unsafe ${q.id}/${field}`);
    }
    if (q.lore.length < 100 || !Number.isInteger(q.contentLevel) || q.contentLevel < 1 || q.contentLevel > 100
        || !Number.isInteger(q.rewardGold) || q.rewardGold < 1 || q.rewardGold > 100) throw new Error(`Invalid expedition budget: ${q.id}`);
    if (q.type === 'KILL') {
        if (!bounds[q.huntingRealm] || typeof q.enemy !== 'string' || !q.enemy.trim()
            || ![q.count, q.minEnemyLevel].every(n => Number.isInteger(n) && n > 0 && n <= 100)
            || q.minEnemyLevel > q.contentLevel || q.sites) throw new Error(`Invalid expedition hunt: ${q.id}`);
    } else {
        if (!q.directions || !Array.isArray(q.sites) || q.sites.length < 1 || q.sites.length > 31) throw new Error(`Invalid expedition investigation: ${q.id}`);
        const [minX,maxX,minZ,maxZ] = bounds[q.realm];
        for (const site of q.sites) {
            if (!/^[a-z_]+$/.test(site.id) || siteIds.has(site.id) || site.entityId !== `chronicle-site-${site.id}`
                || site.kind !== 'inspect' || site.model !== 'command_stone' || !site.title || !site.text || site.text.length < 90
                || !Number.isFinite(site.x) || !Number.isFinite(site.z) || site.x <= minX || site.x >= maxX || site.z <= minZ || site.z >= maxZ) throw new Error(`Invalid expedition discovery: ${q.id}/${site.id}`);
            siteIds.add(site.id);
        }
    }
}
const insertOriginal = (base, additions) => base.flatMap(id => [...additions.filter(q => q.beforeQuestId === id).map(q => q.id), id]);
const base = insertOriginal(insertOriginal(classic, investigations), hunts);
const before = new Map();
for (const q of chapters) {
    if (before.has(q.beforeQuestId)) throw new Error(`Ambiguous expedition chain: ${q.beforeQuestId}`);
    before.set(q.beforeQuestId, q);
}
const order = [], seen = new Set();
function insert(anchor) {
    const q = before.get(anchor);
    if (!q) return;
    if (seen.has(q.id)) throw new Error(`Cyclic expedition chain: ${q.id}`);
    seen.add(q.id); insert(q.id); order.push(q.id);
}
for (const id of base) { insert(id); order.push(id); }
if (seen.size !== chapters.length) throw new Error('Unreachable expedition chain');
for (const q of chapters) {
    const i = order.indexOf(q.id);
    if (order[i-1] !== q.previousQuestId || order[i+1] !== q.beforeQuestId) throw new Error(`Broken expedition handoff: ${q.id}`);
}
for (const q of hunts) {
    if (order[order.indexOf(q.id)-1] !== q.previousQuestId) throw new Error(`Broken original hunt handoff: ${q.id}`);
}
const target = path.join(root, 'src/data/chronicleExpeditions.generated.js');
const output = `// Generated by scripts/generate-chronicle-expeditions.mjs. Do not edit.\nexport const chronicleExpeditions = ${JSON.stringify(chapters, null, 2)};\n`;
if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Stale Chronicle expedition content');
} else fs.writeFileSync(target, output);
console.log(`Verified ${chapters.length} interleaved Chronicle expeditions and their complete story order.`);
