import fs from 'node:fs';
import * as THREE from 'three';
import { createProceduralLanternholdStructure } from '../src/art/ProceduralLanternholdArchitecture.js';
import { createLanternholdNeighborhood } from '../src/art/LanternholdNeighborhood.js';
import { createCasinoHippedRoof } from '../src/art/CasinoFacade.js';
import { LANTERNHOLD_HOMES, LANTERNHOLD_HOME_SCALE } from '../src/data/lanternholdNeighborhood.js';

// Derive support from the rendered slate/canopy/hip triangles. Keep shared
// families local; fifteen houses need fifteen transforms, not fifteen meshes.
const round = value => Math.round(value * 1e6) / 1e6;
const a = new THREE.Vector3(), b = new THREE.Vector3(), c = new THREE.Vector3();
function triangles(root, include) {
    root.updateMatrixWorld(true);
    const result = [];
    root.traverse(mesh => {
        if (!mesh.isMesh || !include(mesh)) return;
        const position = mesh.geometry.attributes.position, indices = mesh.geometry.index;
        for (let i = 0; i < (indices?.count || position.count); i += 3) {
            [a, b, c].forEach((point, offset) => point.fromBufferAttribute(position, indices ? indices.getX(i + offset) : i + offset).applyMatrix4(mesh.matrixWorld));
            // Winding can face either way on a double-sided cloth canopy.
            // Vertical hems/fascia are walls, not traversable support.
            const area = (b.x - a.x) * (c.z - a.z) - (b.z - a.z) * (c.x - a.x);
            if (Math.abs(area) < 1e-7) continue;
            if (mesh.name.endsWith(':frame') && Math.min(a.y, b.y, c.y) < 4.7 * LANTERNHOLD_HOME_SCALE) continue;
            result.push([...a, ...b, ...c].map(round));
        }
    });
    if (!result.length) throw new Error('A town roof lost its authored support triangles');
    return result;
}

const families = {}, placements = [];
const homes = createLanternholdNeighborhood();
families.home = triangles(homes, mesh => /residential-shacks:(roof|frame)$/.test(mesh.name));
LANTERNHOLD_HOMES.forEach((home, index) => placements.push({ id: `town-home-${index}`, family: 'home', x: home.x, y: .025, z: home.z, rotation: home.rotation }));

for (const [family, structure, x, z, rotation] of [
    ['smithy', 'blacksmith', -30, 200, Math.PI / 2],
    ['market', 'trading_post', 30, 200, -Math.PI / 2],
    ['auction', 'trading_house', -22, 185, Math.PI / 4]
]) {
    const root = createProceduralLanternholdStructure(structure);
    families[family] = triangles(root, mesh => /:roof-|:roof-ridge$|tensioned-cloth-canopy$|ridge-pole$/.test(mesh.name));
    // Match WorldGenerator.setupBuilding's optimized bounds and foundation
    // alignment. The auction hall retains its authoritative entity Y instead.
    const rendered = createProceduralLanternholdStructure(structure, { optimized: true });
    rendered.rotation.y = rotation; rendered.updateMatrixWorld(true);
    const y = family === 'auction' ? .5 : -.5 - new THREE.Box3().setFromObject(rendered).min.y;
    placements.push({ id: `town-${family}`, family, x, y: round(y), z, rotation });
}
const casino = new THREE.Mesh(createCasinoHippedRoof());
families.casino = triangles(casino, () => true);
placements.push({ id: 'town-casino', family: 'casino', x: 0, y: 12.55, z: 170, rotation: 0 });

const data = { schemaVersion: 1, families, placements };
const json = JSON.stringify(data) + '\n';
const module = `// Generated by scripts/generate-town-roofs.mjs from current authored architecture.\nexport const TOWN_ROOFS = ${JSON.stringify(data)};\n`;
for (const [target, output] of [
    [new URL('../server/internal/game/content/town-roofs.json', import.meta.url), json],
    [new URL('../src/data/townRoofs.generated.js', import.meta.url), module]
]) {
    if (process.argv.includes('--check')) {
        if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Stale shared town roof support');
    } else fs.writeFileSync(target, output);
}
console.log(`Verified ${placements.length} town roofs in ${Object.keys(families).length} authored families (${Object.values(families).reduce((n, entries) => n + entries.length, 0)} support triangles).`);
