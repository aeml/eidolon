import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const hunts = JSON.parse(fs.readFileSync(path.join(root, 'server/internal/game/content/chronicle-hunts.json'), 'utf8'));
const investigations = JSON.parse(fs.readFileSync(path.join(root, 'server/internal/game/content/chronicle-investigations.json'), 'utf8')).chapters;
const classicIds = [...fs.readFileSync(path.join(root, 'server/internal/game/quests.go'), 'utf8').matchAll(/"(chronicle_\d+_[a-z_]+)"/g)].map(match => match[1]);
const existing = new Set([...classicIds, ...investigations.map(chapter => chapter.id)]);
const ids = new Set(), anchors = new Set();
for (const hunt of hunts) {
    if (!/^chronicle_[a-z_]+$/.test(hunt.id) || ids.has(hunt.id) || existing.has(hunt.id) || anchors.has(hunt.beforeQuestId)
        || !existing.has(hunt.beforeQuestId) || !existing.has(hunt.previousQuestId)) throw new Error(`Invalid hunt placement: ${hunt.id}`);
    for (const field of ['title', 'acceptance', 'completion', 'handoff', 'lore', 'catchupAcceptance', 'catchupCompletion', 'enemy']) {
        if (typeof hunt[field] !== 'string' || !hunt[field].trim()) throw new Error(`Missing ${hunt.id}/${field}`);
    }
    for (const field of ['realm', 'huntingRealm']) {
        if (!['earth', 'water', 'fire', 'air'].includes(hunt[field])) throw new Error(`Invalid ${hunt.id}/${field}`);
    }
    if (![hunt.count, hunt.minEnemyLevel, hunt.contentLevel].every(value => Number.isInteger(value) && value > 0 && value <= 100)
        || hunt.minEnemyLevel > hunt.contentLevel) throw new Error(`Invalid hunt budget: ${hunt.id}`);
    ids.add(hunt.id); anchors.add(hunt.beforeQuestId);
}
if (hunts.length !== 8) throw new Error('Expected eight authored preparation hunts');
const target = path.join(root, 'src/data/chronicleHunts.generated.js');
const output = `// Generated by scripts/generate-chronicle-hunts.mjs. Do not edit.\nexport const chronicleHunts = ${JSON.stringify(hunts, null, 2)};\n`;
if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Stale Chronicle hunt content');
} else fs.writeFileSync(target, output);
console.log('Verified eight authored Chronicle hunts and their existing story anchors.');
